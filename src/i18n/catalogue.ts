export const CATALOGUES: Record<Language, Record<StringKey, string>> = {
  en,
  fr,
  de,
  ar,
};

/** The language the reader chose, or English. */
export function readLanguage(): Language {
  if (typeof window === "undefined") {
    return DEFAULT;
  }
  const stored = window.localStorage.getItem("idm-clone.language");
  return LANGUAGES.find((entry) => entry.code === stored)?.code ?? DEFAULT;
}

/** The entry for a language, so the direction matches the words. */
export function languageEntry(language: Language): LanguageEntry {
  return LANGUAGES.find((entry) => entry.code === language) ?? LANGUAGES[0];
}

/** One word the app shows, in the chosen language. A missing key is English. */
export function translate(language: Language, key: StringKey): string {
  return CATALOGUES[language][key] ?? CATALOGUES.en[key];
}
