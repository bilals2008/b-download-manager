/**
 * The languages the app speaks.
 *
 * One catalogue per language, one key per word. Every key exists in every
 * catalogue, and the checker fails the build when one does not. A missing
 * key reads as English, never as a blank.
 */

export type Language = "en" | "fr" | "de" | "ar";

export interface LanguageEntry {
  /** The code the reader sees and stores. */
  code: Language;
  /** The name of the language in the language itself. */
  label: string;
  /** Whether the window reads right to left. */
  rtl: boolean;
}

