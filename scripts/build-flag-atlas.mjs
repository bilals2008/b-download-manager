// Writes `src/assets/flags.png` and `src/lib/flags.ts`: every country's flag as
// one picture, so a window draws a server's flag from one cell instead of
// loading a file of its own.
//
// The pictures are lipis/flag-icons 7.6.0 (MIT, © Panayiotis Lipiridis and
// contributors), the 4x3 SVGs, as the `flag-icons` package ships them — the
// same set the reference product draws its atlas from. The package's licence
// text is in `node_modules/flag-icons/LICENSE`. Run this after that package is
// updated:
//
//   node scripts/build-flag-atlas.mjs
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import sharp from "sharp";

/// One cell, twice the size it is drawn at: a 16 by 12 flag on a screen that
/// has twice as many pixels in every direction still has its own pixels.
const CELL_WIDTH = 32;
const CELL_HEIGHT = 24;
const COLUMNS = 16;

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "node_modules", "flag-icons", "flags", "4x3");
const codes = readdirSync(source)
  .filter((name) => name.endsWith(".svg"))
  .map((name) => name.slice(0, -".svg".length).toLowerCase())
  .sort();

if (codes.length === 0) {
  throw new Error(`no flags in ${source}; run pnpm install first`);
}

const cells = [];
for (const [index, code] of codes.entries()) {
  const cell = await sharp(join(source, `${code}.svg`), { density: 288 })
    .resize(CELL_WIDTH, CELL_HEIGHT, { fit: "fill" })
    .png()
    .toBuffer();
  cells.push({
    input: cell,
    left: (index % COLUMNS) * CELL_WIDTH,
    top: Math.floor(index / COLUMNS) * CELL_HEIGHT,
  });
}

const rows = Math.ceil(codes.length / COLUMNS);
const atlas = join(root, "src", "assets", "flags.png");
mkdirSync(dirname(atlas), { recursive: true });
await sharp({
  create: {
    width: COLUMNS * CELL_WIDTH,
    height: rows * CELL_HEIGHT,
    channels: 4,
    background: { r: 0, g: 0, b: 0, alpha: 0 },
  },
})
  .composite(cells)
  .png({ compressionLevel: 9, palette: true, quality: 92 })
  .toFile(atlas);

const listing = [];
for (let index = 0; index < codes.length; index += 12) {
  listing.push(`  ${codes.slice(index, index + 12).map((code) => `"${code}"`).join(", ")},`);
}

writeFileSync(
  join(root, "src", "lib", "flags.ts"),
  `// Generated by scripts/build-flag-atlas.mjs — do not edit by hand.
//
// The flags are lipis/flag-icons 7.6.0 (MIT, © Panayiotis Lipiridis and
// contributors), rasterised at ${CELL_WIDTH} by ${CELL_HEIGHT} and laid out
// ${COLUMNS} to a row. The package's licence text is in
// node_modules/flag-icons/LICENSE.
import atlasUrl from "@/assets/flags.png";

/** How the atlas is drawn: one flag per cell, ${COLUMNS} cells to a row. */
export const FLAG_ATLAS = {
  url: atlasUrl,
  columns: ${COLUMNS},
  rows: ${rows},
  cellWidth: ${CELL_WIDTH},
  cellHeight: ${CELL_HEIGHT},
} as const;

/** The country of each cell, in reading order. */
const CODES = [
${listing.join("\n")}
];

/**
 * Where a country's flag is in the atlas, or nothing.
 *
 * The code is an ISO 3166-1 alpha-2 code as the engine reports it (\`IN\`), in
 * either case. Anything that is not two letters has no flag, and a country the
 * atlas does not carry has none either.
 */
export function flagCell(
  code: string | null | undefined,
): { x: number; y: number } | null {
  const key = code?.trim().toLowerCase();
  if (!key || key.length !== 2) {
    return null;
  }
  const index = CODES.indexOf(key);
  if (index < 0) {
    return null;
  }
  return {
    x: (index % FLAG_ATLAS.columns) * FLAG_ATLAS.cellWidth,
    y: Math.floor(index / FLAG_ATLAS.columns) * FLAG_ATLAS.cellHeight,
  };
}
`,
);

console.log(`wrote ${codes.length} flags to src/assets/flags.png (${rows} rows)`);
